create policy "suggestions own read" on public.suggestions for select to authenticated using (user_id=auth.uid() or public.is_admin());
drop policy if exists "suggestions admin manage" on public.suggestions;
create policy "suggestions admin manage" on public.suggestions for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "lecture progress own access" on public.lecture_progress;
create policy "lecture progress own access" on public.lecture_progress for all to authenticated using (user_id=auth.uid() or public.is_admin()) with check (user_id=auth.uid() or public.is_admin());
drop policy if exists "learning activity own read" on public.learning_activity;
create policy "learning activity own read" on public.learning_activity for select to authenticated using (user_id=auth.uid() or public.is_admin());
drop policy if exists "learning activity own insert" on public.learning_activity;
create policy "learning activity own insert" on public.learning_activity for insert to authenticated with check (user_id=auth.uid() or public.is_admin());

drop policy if exists "published course files read" on storage.objects;
create policy "published course files read" on storage.objects for select to authenticated using (bucket_id='course-resources' and (public.is_admin() or exists(select 1 from public.unit_notes n where n.storage_path=name and n.published) or exists(select 1 from public.sample_papers p where p.storage_path=name and p.published) or exists(select 1 from public.units u where u.hero_image_url=name and u.published)));
drop policy if exists "course files admin insert" on storage.objects;
create policy "course files admin insert" on storage.objects for insert to authenticated with check (bucket_id='course-resources' and public.is_admin());
drop policy if exists "course files admin update" on storage.objects;
create policy "course files admin update" on storage.objects for update to authenticated using (bucket_id='course-resources' and public.is_admin()) with check (bucket_id='course-resources' and public.is_admin());
drop policy if exists "course files admin delete" on storage.objects;
create policy "course files admin delete" on storage.objects for delete to authenticated using (bucket_id='course-resources' and public.is_admin());
