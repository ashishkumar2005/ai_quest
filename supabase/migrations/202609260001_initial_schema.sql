-- Student-safe quiz delivery. The answer key never appears in direct student table access.
create or replace function public.get_student_quiz(p_unit_id integer)
returns jsonb language plpgsql stable security definer set search_path = public
as $$
declare result jsonb;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select jsonb_build_object('quiz_id',q.id,'title',q.title,'questions',coalesce(jsonb_agg(jsonb_build_object('id',qq.id,'prompt',qq.question_text,'type',qq.question_type,'options',qq.options,'position',qq.position) order by qq.position) filter (where qq.id is not null),'[]'::jsonb))
  into result from public.quizzes q join public.units u on u.id=q.unit_id
  left join public.quiz_questions qq on qq.quiz_id=q.id and qq.published
  where q.unit_id=p_unit_id and q.published and u.published
  group by q.id order by q.created_at desc limit 1;
  return result;
end;
$$;

create or replace function public.submit_student_quiz(p_unit_id integer,p_answers jsonb)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare qrow public.quizzes%rowtype; total integer; correct integer; score integer; feedback jsonb; attempt uuid;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if jsonb_typeof(p_answers) <> 'array' then raise exception 'Answers must be an array'; end if;
  select q.* into qrow from public.quizzes q join public.units u on u.id=q.unit_id where q.unit_id=p_unit_id and q.published and u.published order by q.created_at desc limit 1;
  if qrow.id is null then raise exception 'Quiz not found'; end if;
  select count(*),count(*) filter (where (p_answers->>(qq.position))::integer=qq.correct_option),
    jsonb_agg(jsonb_build_object('id',qq.id,'prompt',qq.question_text,'options',qq.options,'selected_option',coalesce((p_answers->>(qq.position))::integer,-1),'correct_option',qq.correct_option,'correct',(p_answers->>(qq.position))::integer=qq.correct_option,'explanation',qq.explanation) order by qq.position)
  into total,correct,feedback from public.quiz_questions qq where qq.quiz_id=qrow.id and qq.published;
  if total=0 then raise exception 'Quiz has no published questions'; end if;
  score=round((correct::numeric/total)*100)::integer;
  insert into public.quiz_attempts(user_id,quiz_id,unit_id,score_percent,correct_answers,total_questions,answers)
  values(auth.uid(),qrow.id,p_unit_id,score,correct,total,p_answers) returning id into attempt;
  insert into public.learning_activity(user_id,activity_type,entity_type,entity_id,details)
  values(auth.uid(),'quiz_submitted','unit',p_unit_id::text,jsonb_build_object('score_percent',score));
  return jsonb_build_object('attempt_id',attempt,'score_percent',score,'correct_answers',correct,'total_questions',total,'results',feedback);
end;
$$;
grant execute on function public.get_student_quiz(integer) to authenticated;
grant execute on function public.submit_student_quiz(integer,jsonb) to authenticated;
revoke execute on function public.get_student_quiz(integer) from public;
revoke execute on function public.submit_student_quiz(integer,jsonb) from public;

create or replace function public.admin_reorder_units(p_unit_ids integer[])
returns void language plpgsql security definer set search_path = public
as $$
declare offset_value integer; existing_count integer;
begin
  if not public.is_admin() then raise exception 'Administrator access required'; end if;
  select count(*) into existing_count from public.units where course_id='00000000-0000-4000-8000-000000000010';
  if cardinality(p_unit_ids) <> existing_count or exists(select 1 from public.units where course_id='00000000-0000-4000-8000-000000000010' and not (id=any(p_unit_ids))) then
    raise exception 'Provide every current course unit exactly once';
  end if;
  select coalesce(max(position),0)+existing_count+1 into offset_value from public.units where course_id='00000000-0000-4000-8000-000000000010';
  update public.units set position=offset_value+array_position(p_unit_ids,id) where course_id='00000000-0000-4000-8000-000000000010';
  update public.units set position=array_position(p_unit_ids,id)-1 where course_id='00000000-0000-4000-8000-000000000010';
end;
$$;
revoke execute on function public.admin_reorder_units(integer[]) from public;
grant execute on function public.admin_reorder_units(integer[]) to authenticated;

